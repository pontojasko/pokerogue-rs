import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "original/src/data/type.ts");
const source = readFileSync(sourcePath, "utf8");
const match = source.match(/function getTypeChartMultiplier\([\s\S]*?\n}\n\n\/\*\*/);
if (!match) throw new Error("Could not extract getTypeChartMultiplier from original/src/data/type.ts");
const functionSource = match[0].replace(/\n\n\/\*\*$/, "");
const types = [
  "NORMAL", "FIGHTING", "FLYING", "POISON", "GROUND", "ROCK", "BUG", "GHOST", "STEEL",
  "FIRE", "WATER", "GRASS", "ELECTRIC", "PSYCHIC", "ICE", "DRAGON", "DARK", "FAIRY", "STELLAR",
];
const values = Object.fromEntries(["UNKNOWN", ...types].map((type, i) => [type, i - 1]));
const tempDir = mkdtempSync(path.join(os.tmpdir(), "pokerogue-types-"));
const tempFile = path.join(tempDir, "chart.ts");
const execution = `const PokemonType = ${JSON.stringify(values)};\n${functionSource}\nconst types = ${JSON.stringify(types)};\nconsole.log(JSON.stringify(types.map(a => types.map(d => getTypeChartMultiplier(PokemonType[a], PokemonType[d])))));\n`;
try {
  writeFileSync(tempFile, execution);
  const matrix = JSON.parse(execFileSync(process.execPath, [tempFile], { encoding: "utf8" }));
  const regularTypes = types.slice(0, 18);
  const regular = matrix.slice(0, 18).map((row) => row.slice(0, 18));
  const rust = `// Generated by scripts/extract_type_chart.mjs from original/src/data/type.ts.\nuse crate::Element;\n\nconst CHART: [[u8; 18]; 18] = [\n${regular.map((row) => `    [${row.map((value) => value === 0 ? 0 : value === 0.5 ? 1 : value === 1 ? 2 : 4).join(", ")}],`).join("\n")}\n];\n\npub const fn single_type_effectiveness(attack: Element, defense: Element) -> f32 {\n    match CHART[attack as usize][defense as usize] {\n        0 => 0.0,\n        1 => 0.5,\n        2 => 1.0,\n        4 => 2.0,\n        _ => unreachable!(),\n    }\n}\n`;
  writeFileSync(path.join(root, "pokerogue-data/src/type_chart.rs"), rust);
  const fixture = regularTypes.map((attack, ai) => regularTypes.map((defense, di) => `${attack},${defense},${regular[ai][di]}`).join("\n")).join("\n") + "\n";
  writeFileSync(path.join(root, "pokerogue-tests/fixtures/type-chart.csv"), fixture);
  const damageFixture = [
    ["vine-whip-vs-fire", 5, 45, 9, 9, 100, 1.5, regular[11][9], "Bulbasaur Grass", "Charmander Fire"],
    ["ember-vs-grass-poison", 5, 40, 11, 11, 100, 1.5, regular[9][11] * regular[9][3], "Charmander Fire", "Bulbasaur Grass/Poison"],
    // Matches the base-damage case in original/test/tests/battle/damage-calculation.test.ts.
    ["original-tackle-damage-test", 100, 40, 80, 90, 100, 1, 1, "Charizard mocked Attack 80", "Snorlax mocked Defense 90"],
  ].map(([name, level, power, attack, defense, random, stab, typeMultiplier, attacker, defender]) => {
    const base = ((2 * level / 5 + 2) * power * attack / defense / 50) + 2;
    const result = Math.max(Math.floor(base * 1 * 1 * 1 * 1 * 1 * random / 100 * stab * typeMultiplier * 1 * 1 * 1), 1);
    return `${name},${result},${base},${stab},${typeMultiplier},${attacker},${defender}`;
  }).join("\n") + "\n";
  writeFileSync(path.join(root, "pokerogue-tests/fixtures/damage.csv"), damageFixture);
  console.log(`Extracted ${regularTypes.length}x${regularTypes.length} regular type chart and damage fixtures.`);
} finally {
  rmSync(tempDir, { recursive: true, force: true });
}
