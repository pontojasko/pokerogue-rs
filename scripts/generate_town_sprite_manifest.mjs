#!/usr/bin/env node
// Generate the client sprite-frame manifest from pinned Town data and local
// pokerogue-assets atlas metadata. The image files remain in the assets checkout.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const dataPath = path.join(root, "pokerogue-data/src/generated_data.rs");
const assetsRoot = path.join(root, "original/assets/images/pokemon");
const outputPath = path.join(root, "pokerogue-client/src/generated_sprites.rs");

const data = fs.readFileSync(dataPath, "utf8");
const poolsStart = data.indexOf("pub const TOWN_ENCOUNTER_POOLS");
if (poolsStart < 0) throw new Error("Town encounter data not found");
const poolsEnd = data.indexOf("\n];", poolsStart);
const ids = [...new Set([...data.slice(poolsStart, poolsEnd).matchAll(/\((\d+), "/g)].map(match => Number(match[1])))]
  .concat([1, 4]);
ids.sort((a, b) => a - b);

const rustArray = (values) => `[${values.join(", ")}]`;
const rustFrame = (frame) => {
  const rect = [frame.frame.x, frame.frame.y, frame.frame.w, frame.frame.h];
  const source = [frame.sourceSize.w, frame.sourceSize.h];
  const offset = [frame.spriteSourceSize.x, frame.spriteSourceSize.y];
  const size = [frame.spriteSourceSize.w, frame.spriteSourceSize.h];
  return `    SpriteFrame { rect: ${rustArray(rect)}, source: ${rustArray(source)}, offset: ${rustArray(offset)}, size: ${rustArray(size)} },`;
};

const readFrames = (speciesId, side) => {
  const filename = side === "back" ? `${speciesId}.json` : `${speciesId}.json`;
  const metadataPath = side === "back"
    ? path.join(assetsRoot, "back", filename)
    : path.join(assetsRoot, filename);
  if (!fs.existsSync(metadataPath)) return [];
  const atlas = JSON.parse(fs.readFileSync(metadataPath, "utf8"));
  // Most assets use TexturePacker's textures[0].frames form; a few older
  // Town atlases (e.g. Lechonk/Fidough) use Aseprite's top-level frames list.
  const frames = atlas.textures?.[0]?.frames ?? atlas.frames ?? [];
  return frames
    .filter(frame => /^\d{4}\.png$/.test(frame.filename) && !frame.rotated)
    .sort((a, b) => Number.parseInt(a.filename, 10) - Number.parseInt(b.filename, 10));
};

const records = [];
for (const id of ids) {
  const front = readFrames(id, "front");
  const back = readFrames(id, "back");
  if (front.length === 0 || back.length === 0) continue;
  records.push({ id, front, back });
}

const lines = [
  "// @generated by scripts/generate_town_sprite_manifest.mjs; do not edit.",
  "#[derive(Clone, Copy)]",
  "#[rustfmt::skip]",
  "pub struct SpriteFrame { pub rect: [u16; 4], pub source: [u16; 2], pub offset: [u16; 2], pub size: [u16; 2] }",
  "#[rustfmt::skip]",
  "pub struct SpeciesSpriteFrames { pub id: u16, pub front: &'static [SpriteFrame], pub back: &'static [SpriteFrame] }",
];

for (const record of records) {
  for (const side of ["front", "back"]) {
    lines.push("#[rustfmt::skip]");
    lines.push(`static ${side.toUpperCase()}_${record.id}: &[SpriteFrame] = &[`);
    lines.push(...record[side].map(rustFrame));
    lines.push("];\n");
  }
}

lines.push("#[rustfmt::skip]");
lines.push("pub static TOWN_SPRITE_FRAMES: &[SpeciesSpriteFrames] = &[");
for (const { id } of records) {
  lines.push(`    SpeciesSpriteFrames { id: ${id}, front: FRONT_${id}, back: BACK_${id} },`);
}
lines.push("];");
lines.push("#[rustfmt::skip]");
lines.push("pub fn sprite_frames(id: u16) -> Option<&'static SpeciesSpriteFrames> { TOWN_SPRITE_FRAMES.iter().find(|entry| entry.id == id) }");
const generated = `${lines.join("\n")}\n`;

if (process.argv.includes("--check")) {
  // cargo fmt formats generated Rust source; compare tokens while ignoring
  // whitespace so formatting does not make this deterministic check fail.
  const normalize = (source) => source
    .replace(/,\s*([}\]])/g, "$1")
    .replace(/,\s*\)/g, ")")
    .replace(/\s+/g, "");
  if (!fs.existsSync(outputPath) || normalize(fs.readFileSync(outputPath, "utf8")) !== normalize(generated)) {
    console.error("Town sprite manifest is stale.");
    process.exit(1);
  }
  console.log(`Town sprite manifest is current (${records.length}/${ids.length} species).`);
} else {
  fs.writeFileSync(outputPath, generated);
  console.log(`Generated ${outputPath} (${records.length}/${ids.length} species).`);
}
