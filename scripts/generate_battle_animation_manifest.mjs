#!/usr/bin/env node
// Extract only the two move animations used by the current imported battle moves.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const assets = path.join(root, "original/assets");
const output = path.join(root, "pokerogue-client/src/generated_battle_anims.rs");
const moves = [
  { name: "TACKLE", id: 33, file: "tackle.json" },
  { name: "EMBER", id: 52, file: "ember.json" },
];
const rustNum = (n) => Number.isInteger(n) ? `${n}.0` : String(n);
const entries = moves.map((move) => {
  const source = JSON.parse(fs.readFileSync(path.join(assets, "battle-anims", move.file), "utf8"));
  const frames = source.frames.map((row) => {
    const graphic = row.find((frame) => frame.target === 2);
    if (!graphic) return "    None,";
    const fields = [
      `frame: ${graphic.graphicFrame}`,
      `x: ${rustNum(graphic.x ?? 0)}`,
      `y: ${rustNum(graphic.y ?? 0)}`,
      `zoom_x: ${rustNum(graphic.zoomX ?? 100)}`,
      `zoom_y: ${rustNum(graphic.zoomY ?? 100)}`,
      `angle: ${rustNum(graphic.angle ?? 0)}`,
      `mirror: ${graphic.mirror ?? false}`,
      `visible: ${graphic.visible ?? true}`,
      `opacity: ${graphic.opacity ?? 255}`,
      `focus: ${graphic.focus ?? 1}`,
      `priority: ${graphic.priority ?? 1}`,
    ];
    return `    Some(AnimGraphicFrame { ${fields.join(", ")} }),`;
  });
  return { ...move, graphic: source.graphic, position: source.position, frames };
});
const lines = [
  "// @generated by scripts/generate_battle_animation_manifest.mjs; do not edit.",
  "#[derive(Clone, Copy)]",
  "pub struct AnimGraphicFrame { pub frame: u16, pub x: f32, pub y: f32, pub zoom_x: f32, pub zoom_y: f32, pub angle: f32, pub mirror: bool, pub visible: bool, pub opacity: u8, pub focus: u8, pub priority: u8 }",
  "pub struct MoveAnimation { pub move_id: u16, pub graphic: &'static str, pub frames: &'static [Option<AnimGraphicFrame>] }",
];
for (const move of entries) {
  lines.push(`static ${move.name}_FRAMES: &[Option<AnimGraphicFrame>] = &[`, ...move.frames, "];");
}
lines.push("pub static MOVE_ANIMATIONS: &[MoveAnimation] = &[");
for (const move of entries) {
  lines.push(`    MoveAnimation { move_id: ${move.id}, graphic: ${JSON.stringify(move.graphic)}, frames: ${move.name}_FRAMES },`);
}
lines.push("];");
lines.push("pub fn for_move(move_id: u16) -> Option<&'static MoveAnimation> { MOVE_ANIMATIONS.iter().find(|animation| animation.move_id == move_id) }");
const generated = `${lines.join("\n")}\n`;
if (process.argv.includes("--check")) {
  const normalize = (text) => text.replace(/,\s*([}\]])/g, "$1").replace(/,\s*\)/g, ")").replace(/\s+/g, "");
  if (!fs.existsSync(output) || normalize(fs.readFileSync(output, "utf8")) !== normalize(generated)) {
    console.error("Battle animation manifest is stale.");
    process.exit(1);
  }
  console.log("Battle animation manifest matches pinned Tackle/Ember JSON.");
} else {
  fs.writeFileSync(output, generated);
  console.log(`Generated ${output} from ${entries.length} source animations.`);
}
