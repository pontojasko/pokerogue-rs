#!/usr/bin/env node
// Extract ordered player modifier-pool declarations from the pinned TS source.
import assert from 'node:assert/strict';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(root, 'original/src/modifier/init-modifier-pools.ts');
const pin = '7c0881255af5cd51992e513ff93c2f71adbe40e0';
const source = readFileSync(sourcePath, 'utf8');
const tiers = ['COMMON', 'GREAT', 'ULTRA', 'ROGUE', 'MASTER'];

function withoutComments(text) {
  let output = '', quote = null, escaped = false, lineComment = false, blockComment = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i], next = text[i + 1];
    if (lineComment) {
      if (c === '\n') { lineComment = false; output += '\n'; } else output += ' ';
    } else if (blockComment) {
      if (c === '*' && next === '/') { blockComment = false; output += '  '; i++; }
      else output += c === '\n' ? '\n' : ' ';
    } else if (quote) {
      output += c;
      if (escaped) escaped = false;
      else if (c === '\\') escaped = true;
      else if (c === quote) quote = null;
    } else if (c === '/' && next === '/') { lineComment = true; output += '  '; i++; }
    else if (c === '/' && next === '*') { blockComment = true; output += '  '; i++; }
    else { output += c; if (c === '"' || c === "'" || c === '`') quote = c; }
  }
  return output;
}

function closing(text, start, open = '[', close = ']') {
  let depth = 0, quote = null, escaped = false;
  for (let i = start; i < text.length; i++) {
    const c = text[i];
    if (quote) {
      if (escaped) escaped = false;
      else if (c === '\\') escaped = true;
      else if (c === quote) quote = null;
    } else if (c === '"' || c === "'" || c === '`') quote = c;
    else if (c === open) depth++;
    else if (c === close && --depth === 0) return i;
  }
  throw new Error(`unclosed ${open}${close} source block`);
}

function splitTopLevel(text, delimiter = ',') {
  const parts = [];
  let start = 0, paren = 0, bracket = 0, brace = 0, quote = null, escaped = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quote) {
      if (escaped) escaped = false;
      else if (c === '\\') escaped = true;
      else if (c === quote) quote = null;
      continue;
    }
    if (c === '"' || c === "'" || c === '`') quote = c;
    else if (c === '(') paren++;
    else if (c === ')') paren--;
    else if (c === '[') bracket++;
    else if (c === ']') bracket--;
    else if (c === '{') brace++;
    else if (c === '}') brace--;
    else if (c === delimiter && paren === 0 && bracket === 0 && brace === 0) {
      parts.push(text.slice(start, i).trim()); start = i + 1;
    }
  }
  parts.push(text.slice(start).trim());
  return parts.filter(Boolean);
}

const parseSource = withoutComments(source);
const rows = [];
for (const [tier, tierIndex] of tiers.map((tier, index) => [tier, index])) {
  const marker = `modifierPool[ModifierTier.${tier}] = [`;
  const at = parseSource.indexOf(marker);
  assert.ok(at >= 0, `missing ${tier} modifier pool`);
  const open = at + marker.length - 1;
  const body = parseSource.slice(open + 1, closing(parseSource, open));
  const elements = splitTopLevel(body).map((entry) => entry.replace(/^\s*\/\*[\s\S]*?\*\/\s*/, ''));
  for (const entry of elements) {
    const id = entry.match(/modifierTypes\.([A-Z0-9_]+)/)?.[1];
    if (!id) continue;
    const start = entry.indexOf('new WeightedModifierType(');
    const openArgs = entry.indexOf('(', start);
    const endArgs = entry.lastIndexOf(')');
    if (endArgs <= openArgs) throw new Error(`cannot parse ${tier}/${id}`);
    const args = splitTopLevel(entry.slice(openArgs + 1, endArgs));
    const weightArg = args[1] ?? '';
    const staticWeight = /^\d+$/.test(weightArg) ? Number(weightArg) : null;
    const maxWeight = /^\d+$/.test(args[2] ?? '') ? Number(args[2]) : null;
    rows.push({ tier, tierIndex, index: rows.filter((row) => row.tier === tier).length, id, staticWeight, maxWeight });
  }
}
assert.ok(rows.length > 50, `unexpectedly small pool catalog: ${rows.length}`);
const csv = [
  `# source=${pin}; ordered initCommonModifierPool through initMasterModifierPool declarations`,
  'pool,tier,tier_index,pool_index,id,static_weight,max_weight',
  ...rows.map((r) => `modifier,${r.tier},${r.tierIndex},${r.index},${r.id},${r.staticWeight ?? 'dynamic'},${r.maxWeight ?? ''}`),
  '',
].join('\n');
const rust = [
  `// @generated by scripts/import_modifier_pool_catalog.mjs from PokéRogue ${pin}; do not edit.`,
  '#[rustfmt::skip]',
  '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
  'pub struct ImportedModifierPoolEntry { pub tier: u8, pub pool_index: u16, pub id: &\'static str, pub static_weight: Option<u16>, pub max_weight: Option<u16> }',
  '#[rustfmt::skip]',
  'pub const IMPORTED_PLAYER_MODIFIER_POOL: &[ImportedModifierPoolEntry] = &[',
  ...rows.map((r) => `    ImportedModifierPoolEntry { tier: ${r.tierIndex}, pool_index: ${r.index}, id: "${r.id}", static_weight: ${r.staticWeight === null ? 'None' : `Some(${r.staticWeight})`}, max_weight: ${r.maxWeight === null ? 'None' : `Some(${r.maxWeight})`} },`),
  '];',
  '',
].join('\n');
const outputs = [
  [resolve(root, 'pokerogue-data/src/generated_modifier_pools.rs'), rust],
  [resolve(root, 'pokerogue-tests/fixtures/modifier-pools.csv'), csv],
];
if (process.argv.includes('--check')) {
  for (const [path, expected] of outputs) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== expected) {
      console.error(`${path.slice(root.length + 1)} is stale`);
      process.exitCode = 1;
    }
  }
} else {
  for (const [path, content] of outputs) writeFileSync(path, content);
}
console.log(`Imported ${rows.length} ordered modifier pool entries from pinned TypeScript.`);
