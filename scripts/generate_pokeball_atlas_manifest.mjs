#!/usr/bin/env node
// Extract the Poke/Great/Ultra frames used by the bounded capture animation.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const input = path.join(root, "original/assets/images/pb.json");
const output = path.join(root, "pokerogue-client/src/generated_pokeballs.rs");
const source = JSON.parse(fs.readFileSync(input, "utf8"));
const frames = source.textures[0].frames.filter((frame) =>
  /^(pb|gb|ub)(|_opening|_open)$/.test(frame.filename),
);
if (frames.length !== 9) throw new Error(`expected 9 ball atlas frames, got ${frames.length}`);
const lines = [
  "// @generated by scripts/generate_pokeball_atlas_manifest.mjs; do not edit.",
  "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
  "pub struct BallFrame {",
  "    pub name: &'static str,",
  "    pub x: u16,",
  "    pub y: u16,",
  "    pub width: u16,",
  "    pub height: u16,",
  "}",
  "pub static BALL_FRAMES: &[BallFrame] = &[",
];
for (const frame of frames) {
  const { x, y, w, h } = frame.frame;
  lines.push(
    `    BallFrame {`,
    `        name: ${JSON.stringify(frame.filename)},`,
    `        x: ${x},`,
    `        y: ${y},`,
    `        width: ${w},`,
    `        height: ${h},`,
    `    },`,
  );
}
lines.push(
  "];",
  "pub fn frame(name: &str) -> Option<BallFrame> {",
  "    BALL_FRAMES.iter().copied().find(|frame| frame.name == name)",
  "}",
);
const generated = `${lines.join("\n")}\n`;
if (process.argv.includes("--check")) {
  if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== generated) {
    console.error("Poké Ball atlas manifest is stale.");
    process.exit(1);
  }
  console.log("Poké Ball atlas manifest matches pinned pb.json.");
} else {
  fs.writeFileSync(output, generated);
  console.log(`Generated ${output} from ${frames.length} atlas frames.`);
}
