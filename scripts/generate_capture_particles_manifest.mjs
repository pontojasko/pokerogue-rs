#!/usr/bin/env node
// Extract the pinned Poké Ball particle atlas rectangles used by capture visuals.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const input = path.join(root, "original/assets/images/effects/pb_particles.json");
const output = path.join(root, "pokerogue-client/src/generated_capture_particles.rs");
const source = JSON.parse(fs.readFileSync(input, "utf8"));
const frames = source.textures[0].frames;
if (frames.length !== 11) throw new Error(`expected 11 particle frames, got ${frames.length}`);
const lines = [
  "// @generated by scripts/generate_capture_particles_manifest.mjs; do not edit.",
  "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
  "pub struct ParticleFrame {",
  "    pub id: u8,",
  "    pub x: u16,",
  "    pub y: u16,",
  "    pub width: u16,",
  "    pub height: u16,",
  "    pub source_width: u16,",
  "    pub source_height: u16,",
  "    pub offset_x: u16,",
  "    pub offset_y: u16,",
  "}",
  "pub static PARTICLE_FRAMES: &[ParticleFrame] = &[",
];
for (const frame of frames) {
  const id = Number.parseInt(frame.filename, 10);
  const { x, y, w, h } = frame.frame;
  const { w: source_width, h: source_height } = frame.sourceSize;
  const { x: offset_x, y: offset_y } = frame.spriteSourceSize;
  lines.push(
    "    ParticleFrame {",
    `        id: ${id},`,
    `        x: ${x},`,
    `        y: ${y},`,
    `        width: ${w},`,
    `        height: ${h},`,
    `        source_width: ${source_width},`,
    `        source_height: ${source_height},`,
    `        offset_x: ${offset_x},`,
    `        offset_y: ${offset_y},`,
    "    },",
  );
}
lines.push(
  "];",
  "pub fn frame(id: u8) -> Option<ParticleFrame> {",
  "    PARTICLE_FRAMES.iter().copied().find(|frame| frame.id == id)",
  "}",
);
const generated = `${lines.join("\n")}\n`;
if (process.argv.includes("--check")) {
  if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== generated) {
    console.error("Capture particle atlas manifest is stale.");
    process.exit(1);
  }
  console.log("Capture particle atlas manifest matches pinned pb_particles.json.");
} else {
  fs.writeFileSync(output, generated);
  console.log(`Generated ${output} from ${frames.length} atlas frames.`);
}
