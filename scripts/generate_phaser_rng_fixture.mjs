import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const modulePath = process.argv[2];
if (!modulePath) {
  throw new Error("Usage: node scripts/generate_phaser_rng_fixture.mjs /path/to/phaser/src/math/random-data-generator/RandomDataGenerator.js");
}
const require = createRequire(import.meta.url);
const RandomDataGenerator = require(path.resolve(modulePath));
const battleSeed = "ParitySeed000000";
const shiftCharCodes = (value, shift) => Array.from(value, (char) =>
  String.fromCharCode(char.charCodeAt(0) + shift)).join("");
const rows = [
  "# Generated by Phaser's own RandomDataGenerator.js; seed ParitySeed000000.",
  "# Turn 1 models SMART_RANDOM selection then hit/damage; turn 2 repeats the stream.",
  "# Columns: turn,range,min,expected",
];
for (const turn of [1, 2]) {
  const rng = new RandomDataGenerator(["fixture-init"]);
  rng.sow([shiftCharCodes(battleSeed, turn << 6)]);
  const calls = [[8, 0], [100, 0], [16, 85], [100, 0], [16, 85]];
  for (const [range, min] of calls.slice(0, turn === 1 ? 5 : 3)) {
    rows.push(`${turn},${range},${min},${rng.integerInRange(min, min + range - 1)}`);
  }
}
writeFileSync(path.join(root, "pokerogue-tests/fixtures/phaser-rng.csv"), `${rows.join("\n")}\n`);
console.log(`Wrote Phaser RNG fixtures using ${modulePath}`);
